CREATE TABLE IF NOT EXISTS currencies (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(12) NOT NULL,
    decimal_places TINYINT UNSIGNED NOT NULL DEFAULT 2,
    is_default TINYINT(1) NOT NULL DEFAULT 0,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS exchange_rates (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    from_currency VARCHAR(10) NOT NULL,
    to_currency VARCHAR(10) NOT NULL,
    rate DECIMAL(18, 8) NOT NULL,
    effective_date DATE NOT NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_exchange_pair_date (from_currency, to_currency, effective_date),
    INDEX idx_exchange_pair (from_currency, to_currency),
    CONSTRAINT fk_er_from FOREIGN KEY (from_currency) REFERENCES currencies(code) ON DELETE CASCADE,
    CONSTRAINT fk_er_to FOREIGN KEY (to_currency) REFERENCES currencies(code) ON DELETE CASCADE,
    CONSTRAINT fk_er_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS income_categories (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    color VARCHAR(20) NOT NULL DEFAULT '#10b981',
    description VARCHAR(255) NULL,
    is_system TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_inc_cat_slug (company_id, slug),
    INDEX idx_inc_cat_deleted (deleted_at),
    CONSTRAINT fk_inc_cat_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS expense_categories (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    color VARCHAR(20) NOT NULL DEFAULT '#ef4444',
    description VARCHAR(255) NULL,
    is_system TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_exp_cat_slug (company_id, slug),
    INDEX idx_exp_cat_deleted (deleted_at),
    CONSTRAINT fk_exp_cat_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    transaction_code VARCHAR(50) NOT NULL UNIQUE,
    type ENUM('income', 'expense') NOT NULL,
    income_category_id BIGINT UNSIGNED NULL,
    expense_category_id BIGINT UNSIGNED NULL,
    employee_id BIGINT UNSIGNED NULL,
    department_id BIGINT UNSIGNED NULL,
    payroll_id BIGINT UNSIGNED NULL,
    original_amount DECIMAL(18, 2) NOT NULL,
    currency_code VARCHAR(10) NOT NULL DEFAULT 'USD',
    exchange_rate DECIMAL(18, 8) NOT NULL DEFAULT 1.00000000,
    base_amount DECIMAL(18, 2) NOT NULL,
    transaction_date DATE NOT NULL,
    due_date DATE NULL,
    payment_method ENUM('cash', 'bank_transfer', 'card', 'check', 'online', 'other') NOT NULL DEFAULT 'bank_transfer',
    status ENUM('completed', 'pending', 'approved', 'cancelled') NOT NULL DEFAULT 'completed',
    reference_number VARCHAR(100) NULL,
    vendor_or_client VARCHAR(191) NULL,
    description TEXT NULL,
    attachment_path VARCHAR(255) NULL,
    attachment_name VARCHAR(255) NULL,
    is_recurring TINYINT(1) NOT NULL DEFAULT 0,
    recurring_frequency ENUM('weekly', 'monthly', 'quarterly', 'yearly') NULL,
    next_recurring_date DATE NULL,
    parent_transaction_id BIGINT UNSIGNED NULL,
    approved_by BIGINT UNSIGNED NULL,
    approved_at TIMESTAMP NULL DEFAULT NULL,
    created_by BIGINT UNSIGNED NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_txn_company_type_date (company_id, type, transaction_date),
    INDEX idx_txn_status (status),
    INDEX idx_txn_employee (employee_id),
    INDEX idx_txn_recurring (is_recurring, next_recurring_date),
    INDEX idx_txn_payroll (payroll_id),
    INDEX idx_txn_deleted (deleted_at),
    CONSTRAINT fk_txn_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_txn_inc_cat FOREIGN KEY (income_category_id) REFERENCES income_categories(id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_exp_cat FOREIGN KEY (expense_category_id) REFERENCES expense_categories(id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_currency FOREIGN KEY (currency_code) REFERENCES currencies(code) ON DELETE RESTRICT,
    CONSTRAINT fk_txn_approver FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
