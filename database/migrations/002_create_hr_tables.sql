CREATE TABLE IF NOT EXISTS employees (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NULL UNIQUE,
    department_id BIGINT UNSIGNED NULL,
    employee_code VARCHAR(40) NOT NULL,
    full_name VARCHAR(191) NOT NULL,
    photo_path VARCHAR(255) NULL,
    date_of_birth DATE NULL,
    gender ENUM('male', 'female', 'other') NULL DEFAULT 'other',
    phone VARCHAR(60) NULL,
    email VARCHAR(191) NULL,
    home_address TEXT NULL,
    position VARCHAR(150) NOT NULL,
    employment_date DATE NOT NULL,
    employment_status ENUM('active', 'on_leave', 'suspended', 'resigned') NOT NULL DEFAULT 'active',
    contract_type ENUM('full_time', 'part_time', 'contract', 'freelance') NOT NULL DEFAULT 'full_time',
    contract_start_date DATE NULL,
    contract_end_date DATE NULL,
    contract_notes TEXT NULL,
    payment_type ENUM('fixed', 'hourly', 'daily', 'project', 'task') NOT NULL DEFAULT 'fixed',
    base_salary DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    hourly_rate DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    daily_rate DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    currency_code VARCHAR(10) NOT NULL DEFAULT 'USD',
    bank_name VARCHAR(150) NULL,
    bank_account_number VARCHAR(120) NULL,
    bank_routing_code VARCHAR(80) NULL,
    payment_notes TEXT NULL,
    emergency_contact_name VARCHAR(150) NULL,
    emergency_contact_phone VARCHAR(60) NULL,
    emergency_contact_relation VARCHAR(80) NULL,
    notes TEXT NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_employees_company_code (company_id, employee_code),
    INDEX idx_employees_department (department_id),
    INDEX idx_employees_status (employment_status),
    INDEX idx_employees_deleted (deleted_at),
    CONSTRAINT fk_employees_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_employees_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE departments
    ADD CONSTRAINT fk_departments_manager
    FOREIGN KEY (manager_employee_id) REFERENCES employees(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS employee_documents (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    employee_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(191) NOT NULL,
    document_type VARCHAR(80) NOT NULL DEFAULT 'contract',
    file_path VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    mime_type VARCHAR(120) NOT NULL,
    file_size BIGINT UNSIGNED NOT NULL DEFAULT 0,
    uploaded_by BIGINT UNSIGNED NULL,
    notes TEXT NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_emp_docs_employee (employee_id),
    INDEX idx_emp_docs_deleted (deleted_at),
    CONSTRAINT fk_emp_docs_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_emp_docs_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
