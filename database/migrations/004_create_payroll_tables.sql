CREATE TABLE IF NOT EXISTS payrolls (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    payroll_code VARCHAR(50) NOT NULL UNIQUE,
    period_year SMALLINT UNSIGNED NOT NULL,
    period_month TINYINT UNSIGNED NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    payment_type ENUM('fixed', 'hourly', 'daily', 'project', 'task') NOT NULL DEFAULT 'fixed',
    base_salary DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    working_days DECIMAL(6, 2) NOT NULL DEFAULT 22.00,
    worked_days DECIMAL(6, 2) NOT NULL DEFAULT 22.00,
    working_hours DECIMAL(8, 2) NOT NULL DEFAULT 176.00,
    overtime_hours DECIMAL(8, 2) NOT NULL DEFAULT 0.00,
    overtime_pay DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    completed_tasks_count INT UNSIGNED NOT NULL DEFAULT 0,
    task_bonus DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    performance_bonus DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    other_bonuses DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    authorized_deductions DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    adjustments DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    gross_salary DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    net_salary DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    currency_code VARCHAR(10) NOT NULL DEFAULT 'USD',
    status ENUM('pending', 'approved', 'paid') NOT NULL DEFAULT 'pending',
    payment_date DATE NULL,
    payment_method ENUM('cash', 'bank_transfer', 'card', 'check', 'online', 'other') NULL DEFAULT 'bank_transfer',
    transaction_id BIGINT UNSIGNED NULL,
    notes TEXT NULL,
    calculated_by BIGINT UNSIGNED NULL,
    paid_by BIGINT UNSIGNED NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_payroll_emp_period (employee_id, period_year, period_month, deleted_at),
    INDEX idx_payroll_company_period (company_id, period_year, period_month),
    INDEX idx_payroll_status (status),
    INDEX idx_payroll_deleted (deleted_at),
    CONSTRAINT fk_payroll_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_payroll_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_payroll_txn FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE SET NULL,
    CONSTRAINT fk_payroll_calc_by FOREIGN KEY (calculated_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_payroll_paid_by FOREIGN KEY (paid_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS salary_components (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    payroll_id BIGINT UNSIGNED NOT NULL,
    component_type ENUM('earning', 'bonus', 'overtime', 'deduction', 'adjustment') NOT NULL,
    code VARCHAR(60) NOT NULL,
    label VARCHAR(150) NOT NULL,
    quantity DECIMAL(10, 2) NOT NULL DEFAULT 1.00,
    rate DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    amount DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    is_authorized TINYINT(1) NOT NULL DEFAULT 1,
    authorized_by BIGINT UNSIGNED NULL,
    notes VARCHAR(255) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_sc_payroll (payroll_id),
    CONSTRAINT fk_sc_payroll FOREIGN KEY (payroll_id) REFERENCES payrolls(id) ON DELETE CASCADE,
    CONSTRAINT fk_sc_authorizer FOREIGN KEY (authorized_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bonuses (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    payroll_id BIGINT UNSIGNED NULL,
    bonus_type ENUM('task', 'performance', 'project', 'holiday', 'spot', 'other') NOT NULL DEFAULT 'performance',
    title VARCHAR(191) NOT NULL,
    amount DECIMAL(18, 2) NOT NULL,
    currency_code VARCHAR(10) NOT NULL DEFAULT 'USD',
    awarded_date DATE NOT NULL,
    status ENUM('pending', 'approved', 'paid', 'cancelled') NOT NULL DEFAULT 'approved',
    approved_by BIGINT UNSIGNED NULL,
    notes TEXT NULL,
    created_by BIGINT UNSIGNED NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_bonuses_emp (employee_id),
    INDEX idx_bonuses_payroll (payroll_id),
    INDEX idx_bonuses_deleted (deleted_at),
    CONSTRAINT fk_bonuses_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_bonuses_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_bonuses_payroll FOREIGN KEY (payroll_id) REFERENCES payrolls(id) ON DELETE SET NULL,
    CONSTRAINT fk_bonuses_approver FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_bonuses_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS deductions (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    payroll_id BIGINT UNSIGNED NULL,
    deduction_type ENUM('tax', 'advance', 'penalty', 'absence', 'insurance', 'other') NOT NULL DEFAULT 'other',
    title VARCHAR(191) NOT NULL,
    amount DECIMAL(18, 2) NOT NULL,
    currency_code VARCHAR(10) NOT NULL DEFAULT 'USD',
    deduction_date DATE NOT NULL,
    is_authorized TINYINT(1) NOT NULL DEFAULT 0,
    authorized_by BIGINT UNSIGNED NULL,
    authorized_at TIMESTAMP NULL DEFAULT NULL,
    status ENUM('pending_confirmation', 'authorized', 'applied', 'waived') NOT NULL DEFAULT 'pending_confirmation',
    notes TEXT NULL,
    created_by BIGINT UNSIGNED NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_deductions_emp (employee_id),
    INDEX idx_deductions_auth (is_authorized, status),
    INDEX idx_deductions_deleted (deleted_at),
    CONSTRAINT fk_deductions_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_deductions_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_deductions_payroll FOREIGN KEY (payroll_id) REFERENCES payrolls(id) ON DELETE SET NULL,
    CONSTRAINT fk_deductions_authorizer FOREIGN KEY (authorized_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_deductions_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    attendance_date DATE NOT NULL,
    status ENUM('present', 'absent', 'late', 'half_day', 'on_leave', 'remote') NOT NULL DEFAULT 'present',
    check_in TIME NULL,
    check_out TIME NULL,
    worked_hours DECIMAL(5, 2) NOT NULL DEFAULT 8.00,
    overtime_hours DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
    notes VARCHAR(255) NULL,
    recorded_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_attendance_emp_date (employee_id, attendance_date),
    INDEX idx_attendance_date (attendance_date),
    CONSTRAINT fk_att_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_att_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_att_recorder FOREIGN KEY (recorded_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
