CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    department_id BIGINT UNSIGNED NULL,
    task_code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(191) NOT NULL,
    description TEXT NULL,
    priority ENUM('low', 'medium', 'high', 'urgent') NOT NULL DEFAULT 'medium',
    status ENUM('pending', 'in_progress', 'completed', 'cancelled') NOT NULL DEFAULT 'pending',
    is_project_task TINYINT(1) NOT NULL DEFAULT 0,
    project_name VARCHAR(150) NULL,
    reward_amount DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    currency_code VARCHAR(10) NOT NULL DEFAULT 'USD',
    deadline DATE NULL,
    completed_at TIMESTAMP NULL DEFAULT NULL,
    completion_notes TEXT NULL,
    progress_percent TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_tasks_status_priority (status, priority),
    INDEX idx_tasks_deadline (deadline),
    INDEX idx_tasks_deleted (deleted_at),
    CONSTRAINT fk_tasks_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_tasks_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
    CONSTRAINT fk_tasks_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS task_assignments (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    task_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    assigned_by BIGINT UNSIGNED NULL,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role_in_task VARCHAR(80) NOT NULL DEFAULT 'assignee',
    reward_share_percent DECIMAL(5, 2) NOT NULL DEFAULT 100.00,
    completion_status ENUM('assigned', 'working', 'submitted', 'verified') NOT NULL DEFAULT 'assigned',
    completed_work_notes TEXT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_task_employee (task_id, employee_id),
    INDEX idx_ta_employee (employee_id),
    CONSTRAINT fk_ta_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
    CONSTRAINT fk_ta_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_ta_assigner FOREIGN KEY (assigned_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS performance_records (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    period_label VARCHAR(80) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    tasks_assigned INT UNSIGNED NOT NULL DEFAULT 0,
    tasks_completed INT UNSIGNED NOT NULL DEFAULT 0,
    tasks_on_time INT UNSIGNED NOT NULL DEFAULT 0,
    attendance_rate DECIMAL(5, 2) NOT NULL DEFAULT 100.00,
    manager_rating DECIMAL(5, 2) NOT NULL DEFAULT 85.00,
    computed_score DECIMAL(5, 2) NOT NULL DEFAULT 85.00,
    recommended_bonus DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    approved_bonus DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    evaluation_rule_snapshot JSON NULL,
    feedback TEXT NULL,
    evaluated_by BIGINT UNSIGNED NULL,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_perf_employee (employee_id),
    INDEX idx_perf_period (period_start, period_end),
    INDEX idx_perf_deleted (deleted_at),
    CONSTRAINT fk_perf_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_perf_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_perf_evaluator FOREIGN KEY (evaluated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
